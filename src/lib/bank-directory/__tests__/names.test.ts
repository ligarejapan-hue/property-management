import { describe, expect, it } from "vitest";
import { formalBankName, formalBranchName, toSearchKey } from "../names";

describe("toSearchKey(検索のための読みの形)", () => {
  it("全角英数を半角・小文字に、カタカナをひらがなに、小さい字を大きい字にそろえる", () => {
    expect(toSearchKey("ＰａｙＰａｙ")).toBe("paypay");
    expect(toSearchKey("ミズホ")).toBe("みずほ");
    expect(toSearchKey("ﾐｽﾞﾎ")).toBe("みずほ");
    // 全銀の読みは小さい字を大きい字で持つ(ゆうちよ)。打つ人は「ゆうちょ」と打つ。
    expect(toSearchKey("ゆうちょ")).toBe(toSearchKey("ゆうちよ"));
    expect(toSearchKey("ッ")).toBe("つ");
  });
  it("長音・ハイフン類は同じ記号に、空白は消す", () => {
    expect(toSearchKey("みつびしゆ－えふじえい")).toBe(toSearchKey("ミツビシユーエフジエイ"));
    expect(toSearchKey("三菱 UFJ")).toBe("三菱ufj");
  });
});

