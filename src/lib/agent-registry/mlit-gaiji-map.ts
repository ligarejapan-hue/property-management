/** 外字(1字) → 置き換える字(1字)。 */
export const MLIT_GAIJI_MAP: ReadonlyMap<string, string> = new Map(ENTRIES.map(([from, to]) => [from, to]));

/** 国交省の画面の文字の中の、表にある外字を普通の字にする。表に無い外字はそのまま。 */
export function replaceMlitGaiji(text: string): string {
  return text.replace(/[\uE000-\uF8FF]/gu, (c) => MLIT_GAIJI_MAP.get(c) ?? c);
}
