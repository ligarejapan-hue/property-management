import { describe, it, expect } from "vitest";
import {
  formatPhoneJp,
  phoneSearchDigits,
  isValidPhoneJp,
  phoneForStore,
  samePhoneNumber,
} from "../phone-format-jp";

// 発注者決定(2026-09-26): 電話番号はハイフンありで統一。ハイフンなしで入れたら自動で入れる。
// 携帯と固定で区切る位置が違う(固定は市外局番が2〜5桁)ので、市外局番表を持つ既製部品で判定する。
describe("formatPhoneJp", () => {
  it.each([
    ["09012345678", "090-1234-5678"], // 携帯
    ["07012345678", "070-1234-5678"],
    ["05012345678", "050-1234-5678"], // IP電話
    ["0312345678", "03-1234-5678"], // 東京(2桁)
    ["0451234567", "045-123-4567"], // 横浜(3桁)
    ["0466123456", "0466-12-3456"], // 藤沢(4桁)
    ["0126712345", "01267-1-2345"], // 5桁の市外局番
    ["0120123456", "0120-123-456"], // フリーダイヤル
    ["08001234567", "0800-123-4567"],
    ["０３１２３４５６７８", "03-1234-5678"], // 全角
  ])("%s → %s", (input, expected) => {
    expect(formatPhoneJp(input)).toEqual({ value: expected, formatted: true });
  });

  it("すでに正しいハイフンなら formatted=false(変えない)", () => {
    expect(formatPhoneJp("090-1234-5678")).toEqual({ value: "090-1234-5678", formatted: false });
  });

  // 発注者決定(2026-09-28): 自動で区切るのは**数字だけで入れたとき**だけ。自分で区切った番号は
  // 区切り位置を変えない(部品の割り当て表が実際と違うときに、人が直せる逃げ道)。
  // 区切りの文字(全角ハイフン・長音・空白・括弧)だけを「-」にそろえる。
  it.each([
    ["0422-12-3456", "0422-12-3456", false], // 部品なら 042-212-3456 に直すが、手の区切りを残す
    ["0312-34-5678", "0312-34-5678", false],
    ["0120-12-3456", "0120-12-3456", false],
    ["03 1234 5678", "03-1234-5678", true], // 空白 → ハイフン(位置はそのまま)
    ["0466 12 3456", "0466-12-3456", true],
    ["０４２２－１２－３４５６", "0422-12-3456", true], // 全角の数字・ハイフン
    ["090ー1234ー5678", "090-1234-5678", true], // 長音で区切った
    ["03(1234)5678", "03-1234-5678", true], // 括弧の区切り
    ["(03)1234-5678", "03-1234-5678", true],
    ["03--1234--5678", "03-1234-5678", true], // 続いた区切りは1つに
  ])("自分で区切った番号は位置を変えない: %s → %s", (input, expected, formatted) => {
    expect(formatPhoneJp(input)).toEqual({ value: expected, formatted });
  });

  // 端にだけ区切りが付いた番号(打ちかけの「-」の消し忘れ・名刺の書き写しなど)は、
  // 区切りを入れたことにならない=数字だけとして自動で区切る。
  it.each([
    ["09012345678-", "090-1234-5678"],
    ["-09012345678", "090-1234-5678"],
    [" (0312345678) ", "03-1234-5678"],
    ["0312345678 ", "03-1234-5678"],
  ])("端にだけ区切りがある番号は自動で区切る: %s → %s", (input, expected) => {
    expect(formatPhoneJp(input)).toEqual({ value: expected, formatted: true });
  });

  it("空は空のまま", () => {
    expect(formatPhoneJp("")).toEqual({ value: "", formatted: false });
    expect(formatPhoneJp("   ")).toEqual({ value: "", formatted: false });
  });

  it.each([
    ["031234567"], // 9桁(足りない)
    ["0800123456"], // 0800 は 11桁が正しい
    ["12345"],
    ["03-1234-5678 内線12"], // 内線などの文字が付いたものは触らない
    ["+81312345678"], // 国際表記は勝手に変えない
    ["不明"],
  ])("番号として正しくないもの・文字入りは入力どおり(%s)", (input) => {
    expect(formatPhoneJp(input)).toEqual({ value: input.trim(), formatted: false });
  });
});


// 検索語を数字だけにする(保存値側も数字だけにして比べる=ハイフンの有無・打ちかけでも当たる)。
describe("phoneSearchDigits", () => {
  it.each([
    ["09012345678", "09012345678"],
    ["090-1234-5678", "09012345678"],
    ["0901234", "0901234"], // 打ちかけ(7桁)
    ["０９０−１２３４", "0901234"], // 全角
  ])("%s → %s", (q, d) => expect(phoneSearchDigits(q)).toBe(d));
  it.each([["090123"], ["山田"], ["03-1234-5678 内線"], [""]])("6桁以下・数字以外の語は null(%s)", (q) => {
    expect(phoneSearchDigits(q)).toBeNull();
  });
});

// 入力欄を離れたときに「番号を確認してください」を出すかの判定(空は出さない)。
describe("isValidPhoneJp", () => {
  it.each(["09012345678", "090-1234-5678", "03-1234-5678", "0466123456", "０３１２３４５６７８"])("正しい番号は true(%s)", (s) => {
    expect(isValidPhoneJp(s)).toBe(true);
  });
  it.each(["031234567", "0800123456", "12345", "03-1234-5678 内線12", "不明"])("正しくない番号は false(%s)", (s) => {
    expect(isValidPhoneJp(s)).toBe(false);
  });
});

// 取り込み(所有者CSV・取込のやり直し・貼り付けて物件化)も、保存するときに画面と同じ規則で
// そろえる(以前は画面で入れたときだけハイフンが入り、取り込みはハイフンなしのまま入っていた)。
describe("phoneForStore(保存する値)", () => {
  it.each([
    [null, null],
    [undefined, null],
    ["", null],
    ["   ", null],
    ["09012345678", "090-1234-5678"],
    ["0422-12-3456", "0422-12-3456"], // 手の区切りはそのまま
    ["03 1234 5678", "03-1234-5678"],
    ["03-1234-5678 内線12", "03-1234-5678 内線12"], // 文字入りは触らない
  ])("%s → %s", (input, expected) => {
    expect(phoneForStore(input)).toBe(expected);
  });
});

// 重複の判定(@codex P1 #455): 手で区切った番号を残すようになったので、保存済みの書き方は
// 決まった形にならない(0422-12-3456 も 042-212-3456 もありうる)。入ってきた番号から書き方を
// 並べて照らすと取りこぼすため、**両方を数字だけにして**比べる。
describe("samePhoneNumber(同じ番号か)", () => {
  it.each([
    ["0422-12-3456", "0422123456"],
    ["0422123456", "042-212-3456"],
    ["0422-12-3456", "042-212-3456"],
    ["090-1234-5678", "090 1234 5678"],
    ["０９０－１２３４－５６７８", "09012345678"],
  ])("書き方が違っても同じ番号: %s と %s", (a, b) => {
    expect(samePhoneNumber(a, b)).toBe(true);
  });
  it.each([
    ["0422-12-3456", "0422-12-3457"],
    ["03-1234-5678 内線12", "0312345678"], // 文字入りは数字だけにしない(内線の数字を混ぜない)
    ["03-1234-5678", "03-1234-5678 内線12"],
    ["", ""],
    ["   ", "0312345678"],
  ])("違う番号(または比べられない): %s と %s", (a, b) => {
    expect(samePhoneNumber(a, b)).toBe(false);
  });
  it("文字入り同士は書き方が完全に同じときだけ同じ", () => {
    expect(samePhoneNumber("03-1234-5678 内線12", " 03-1234-5678 内線12 ")).toBe(true);
  });
});
