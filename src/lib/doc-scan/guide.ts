/**
 * 書類を撮る —「紙の範囲」の画面に出す説明(純関数)。部品(OpenCV.js)の状態で、保存のときに何が起きるかを正しく言う。
 */
export function scanGuide(found: boolean, cvReady: boolean, cvFailed: boolean): string {
  if (cvFailed) {
    return "紙を自動で見つける部品を読み込めませんでした。角の丸を指で紙の四隅に合わせてください。保存のときは、角で囲んだ長方形で切り取ります(形の直しはしません)。";
  }
  if (!cvReady) {
    return "紙を自動で見つける準備をしています。少しお待ちください。";
  }
  if (!found) {
    return "紙を自動で見つけられませんでした。角の丸を指で紙の四隅に合わせてください。保存のときに、まっすぐ正面から見た形に直します。";
  }
  return "紙の四隅を自動で見つけました。ずれていたら角の丸を指で動かしてください。保存のときに、まっすぐ正面から見た形に直します。";
}
