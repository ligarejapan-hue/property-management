/**
 * 地図の gestureHandling。**"greedy"(1本指で地図移動)に固定** (発注者決定 2026-08-24)。
 *
 * 経緯: 以前のスマホ改修でタッチ端末を "cooperative"(1本指=ページスクロール/
 * 2本指=地図移動)にしていた。目的は「地図が画面を占有して周囲の UI に触れなく
 * なる問題の回避」だったが、この地図(本体・履歴とも)は**画面いっぱいの固定
 * レイアウトで、1本指で送る先のページがほぼ存在しない**。結果、現場の片手操作で
 * 毎回2本指を要求するだけになっていた(操作性点検 B1)。
 *
 * フックの形は残す(呼び出し2箇所を変えずに、判断を1箇所で持つため)。
 * 将来「ページに埋め込む小さな地図」を作る場合は、その呼び出し側でのみ
 * cooperative を選ぶこと(この全画面2画面は greedy が正)。
 */
export function useMapGestureHandling(): "cooperative" | "greedy" {
  return "greedy";
}
